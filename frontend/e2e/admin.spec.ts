import { expect, test } from '@playwright/test';

test('administrator manages a persisted user and reviews its audit events', async ({ page }) => {
  const errors: string[] = [];
  page.on('pageerror', error => errors.push(error.message));
  page.on('console', message => { if (message.type() === 'error') errors.push(message.text()); });
  const password = process.env.E2E_ADMIN_PASSWORD;
  if (!password) throw new Error('Set E2E_ADMIN_PASSWORD after first-use setup');
  const name = `Admin journey ${Date.now()}`;
  const email = `journey${Date.now()}@example.com`;
  await page.goto('/login');
  await page.getByLabel('Email address').fill('admin@ketsip.local');
  await page.getByLabel('Password').fill(password);
  await page.getByRole('button', { name: 'Sign in' }).click();
  await page.getByRole('link', { name: 'Administration' }).click();
  await page.getByRole('button', { name: 'Create user' }).click();
  await page.getByLabel('Name', { exact: true }).fill(name);
  await page.getByLabel('Email', { exact: true }).fill(email);
  await page.getByLabel('Initial password').fill('Journey-password-123');
  await page.getByLabel('Role', { exact: true }).selectOption('Engineer');
  const created = page.waitForResponse(response => response.url().endsWith('/api/users') && response.request().method() === 'POST');
  await page.getByRole('button', { name: 'Save user' }).click();
  const createResponse = await created;
  expect(createResponse.status()).toBe(201);
  const user = await createResponse.json();
  await expect(page.getByRole('heading', { name })).toBeVisible();
  await page.getByRole('button', { name: 'Edit user' }).click();
  await page.getByLabel('Manager name').fill('Journey Manager');
  const updated = page.waitForResponse(response => response.url().endsWith(`/api/users/${user.id}`) && response.request().method() === 'PUT');
  await page.getByRole('button', { name: 'Save user' }).click();
  expect((await updated).status()).toBe(200);
  await expect(page.getByText('Journey Manager')).toBeVisible();
  await page.reload();
  await page.getByRole('button', { name }).click();
  await expect(page.getByText('Journey Manager')).toBeVisible();
  page.once('dialog', dialog => dialog.accept());
  const deleted = page.waitForResponse(response => response.url().endsWith(`/api/users/${user.id}`) && response.request().method() === 'DELETE');
  await page.getByRole('button', { name: 'Deactivate user' }).click();
  expect((await deleted).status()).toBe(204);
  await expect(page.getByText('User deactivated.')).toBeVisible();
  await page.getByRole('link', { name: 'Audit log' }).click();
  await page.getByLabel('Action').selectOption('delete');
  await expect(page.getByText('User deactivated', { exact: true }).first()).toBeVisible();
  const exported = page.waitForResponse(response => response.url().includes('/api/audit-logs/export'));
  await page.getByRole('button', { name: 'Export CSV' }).click();
  expect((await exported).status()).toBe(200);
  expect(errors).toEqual([]);
});

test('administrator edits a role and sees the persisted definition', async ({ page }) => {
  const errors: string[] = [];
  page.on('pageerror', error => errors.push(error.message));
  page.on('console', message => { if (message.type() === 'error') errors.push(message.text()); });
  const password = process.env.E2E_ADMIN_PASSWORD;
  if (!password) throw new Error('Set E2E_ADMIN_PASSWORD after first-use setup');
  await page.goto('/login');
  await page.getByLabel('Email address').fill('admin@ketsip.local');
  await page.getByLabel('Password').fill(password);
  await page.getByRole('button', { name: 'Sign in' }).click();
  await page.getByRole('link', { name: 'Administration' }).click();
  const listed = page.waitForResponse(response => response.url().includes('/api/roles?') && response.request().method() === 'GET');
  await page.getByRole('link', { name: 'Roles' }).click();
  const listResponse = await listed;
  expect(listResponse.status()).toBe(200);
  const original = (await listResponse.json()).items.find((role: { name: string }) => role.name === 'Engineer');
  expect(original).toBeTruthy();
  const description = `E2E role ${Date.now()}`;
  await page.getByRole('button', { name: 'Engineer' }).click();
  try {
    await page.getByLabel('Description').fill(description);
    const saved = page.waitForResponse(response => response.url().endsWith(`/api/roles/${original.id}`) && response.request().method() === 'PUT');
    await page.getByRole('button', { name: 'Save role' }).click();
    const response = await saved;
    expect(response.status()).toBe(200);
    expect((await response.json()).description).toBe(description);
    await expect(page.getByText('Role saved.')).toBeVisible();
    await page.reload();
    await page.getByRole('button', { name: 'Engineer' }).click();
    await expect(page.getByLabel('Description')).toHaveValue(description);
  } finally {
    await page.getByLabel('Description').fill(original.description);
    const restored = page.waitForResponse(response => response.url().endsWith(`/api/roles/${original.id}`) && response.request().method() === 'PUT');
    await page.getByRole('button', { name: 'Save role' }).click();
    expect((await restored).status()).toBe(200);
  }
  expect(errors).toEqual([]);
});

test('auditor reads and exports filtered live audit events', async ({ page }) => {
  const errors: string[] = [];
  page.on('pageerror', error => errors.push(error.message));
  page.on('console', message => { if (message.type() === 'error') errors.push(message.text()); });
  const password = process.env.E2E_AUDITOR_PASSWORD;
  if (!password) throw new Error('Set E2E_AUDITOR_PASSWORD for the seeded auditor');
  await page.goto('/login');
  await page.getByLabel('Email address').fill('auditor@ketsip.local');
  await page.getByLabel('Password').fill(password);
  await page.getByRole('button', { name: 'Sign in' }).click();
  await page.getByRole('link', { name: 'Administration' }).click();
  await expect(page.getByRole('link', { name: 'Users', exact: true })).toHaveCount(0);
  await expect(page.getByRole('link', { name: 'Roles', exact: true })).toHaveCount(0);
  const filtered = page.waitForResponse(response => response.url().includes('/api/audit-logs?') && response.url().includes('action=login'));
  await page.getByLabel('Action').selectOption('login');
  const response = await filtered;
  expect(response.status()).toBe(200);
  const events = (await response.json()).items;
  expect(events.length).toBeGreaterThan(0);
  expect(events.every((event: { action: string }) => event.action === 'login')).toBe(true);
  await expect(page.getByText(events[0].details, { exact: true }).first()).toBeVisible();
  const exported = page.waitForResponse(response => response.url().includes('/api/audit-logs/export?') && response.url().includes('action=login'));
  await page.getByRole('button', { name: 'Export CSV' }).click();
  const csv = await exported;
  expect(csv.status()).toBe(200);
  expect(csv.headers()['content-type']).toContain('text/csv');
  const content = await csv.text();
  expect(content).toContain('timestamp,userId');
  expect(content).toContain(events[0].userId);
  await expect(page.getByText('Audit log exported.')).toBeVisible();
  expect(errors).toEqual([]);
});
