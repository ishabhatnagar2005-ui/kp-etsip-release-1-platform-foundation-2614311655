import { expect, test } from '@playwright/test';
import { readFile } from 'node:fs/promises';

test('executive navigates reports and downloads scoped inventory', async ({ page }) => {
  const errors: string[] = [];
  page.on('pageerror', error => errors.push(error.message));
  page.on('console', message => { if (message.type() === 'error') errors.push(message.text()); });
  const password = process.env.E2E_DEMO_PASSWORD;
  if (!password) throw new Error('Set E2E_DEMO_PASSWORD to the seeded demo password');
  await page.goto('/login');
  await page.getByLabel('Email address').fill('executive@ketsip.local');
  await page.getByLabel('Password').fill(password);
  await page.getByRole('button', { name: 'Sign in' }).click();
  await page.getByRole('link', { name: 'Applications', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Applications' })).toBeVisible();
  const firstReport = page.waitForResponse(response => response.url().includes('/api/reports/applications?') && !response.url().includes('format=csv'));
  await page.getByRole('link', { name: 'Reports', exact: true }).click();
  const first = await firstReport;
  expect(first.status()).toBe(200);
  const data = await first.json();
  expect(data.items.length).toBeGreaterThan(0);
  await expect(page.getByRole('link', { name: data.items[0].name, exact: true })).toBeVisible();
  const filtered = page.waitForResponse(response => response.url().includes('/api/reports/applications?') && new URL(response.url()).searchParams.get('search') === data.items[0].name);
  await page.getByLabel('Search').fill(data.items[0].name);
  const filteredResponse = await filtered;
  expect(filteredResponse.status()).toBe(200);
  expect((await filteredResponse.json()).items.some((item: { id: string }) => item.id === data.items[0].id)).toBeTruthy();
  const csvResponse = page.waitForResponse(response => response.url().includes('/api/reports/applications?') && new URL(response.url()).searchParams.get('format') === 'csv');
  const download = page.waitForEvent('download');
  await page.getByRole('button', { name: 'Export CSV' }).click();
  expect((await csvResponse).status()).toBe(200);
  const file = await download;
  expect(file.suggestedFilename()).toBe('applications.csv');
  expect(await readFile(await file.path(), 'utf8')).toContain(data.items[0].name);
  const portfolioResponse = page.waitForResponse(response => response.url().includes('/api/reports/portfolios?'));
  await page.getByRole('link', { name: 'Portfolio Report' }).click();
  const portfolioData = await (await portfolioResponse).json();
  expect(portfolioData.items.length).toBeGreaterThan(0);
  await expect(page.getByRole('link', { name: portfolioData.items[0].name, exact: true })).toBeVisible();
  const portfolioCsv = page.waitForResponse(response => response.url().includes('/api/reports/portfolios?') && new URL(response.url()).searchParams.get('format') === 'csv');
  const portfolioDownload = page.waitForEvent('download');
  await page.getByRole('button', { name: 'Export CSV' }).click();
  expect((await portfolioCsv).status()).toBe(200);
  expect(await readFile(await (await portfolioDownload).path(), 'utf8')).toContain(portfolioData.items[0].name);
  await page.getByRole('link', { name: 'Applications', exact: true }).click();
  const repositoryCsv = page.waitForResponse(response => response.url().includes('/api/reports/applications?') && new URL(response.url()).searchParams.get('format') === 'csv');
  const repositoryDownload = page.waitForEvent('download');
  await page.getByRole('button', { name: 'Export CSV' }).click();
  expect((await repositoryCsv).status()).toBe(200);
  expect(await readFile(await (await repositoryDownload).path(), 'utf8')).toContain('portfolioId');
  expect(errors).toEqual([]);
});
