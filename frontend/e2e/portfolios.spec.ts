import { expect, test } from '@playwright/test';

test('administrator creates, edits, filters and deletes a persisted portfolio', async ({ page }) => {
  const errors: string[] = [];
  page.on('pageerror', error => errors.push(error.message));
  page.on('console', message => { if (message.type() === 'error') errors.push(message.text()); });
  const password = process.env.E2E_ADMIN_PASSWORD;
  if (!password) throw new Error('Set E2E_ADMIN_PASSWORD to the current administrator password after first-use setup');
  const name = `Journey ${Date.now()}`;
  await page.goto('/login');
  await page.getByLabel('Email address').fill('admin@ketsip.local');
  await page.getByLabel('Password').fill(password);
  await page.getByRole('button', { name: 'Sign in' }).click();
  await page.getByRole('link', { name: 'Portfolios' }).click();
  await page.getByRole('link', { name: 'Create portfolio' }).click();
  await page.getByLabel('Name').fill(name);
  await page.getByLabel('Owner').fill('Journey Owner');
  await page.getByLabel('Product area').fill('Journey Area');
  const created = page.waitForResponse(response => response.url().endsWith('/api/portfolios') && response.request().method() === 'POST');
  await page.getByRole('button', { name: 'Save portfolio' }).click();
  const createResponse = await created;
  expect(createResponse.status()).toBe(201);
  const portfolio = await createResponse.json();
  await expect(page.getByRole('heading', { name })).toBeVisible();
  await page.getByRole('link', { name: 'Edit portfolio' }).click();
  await page.getByLabel('Owner').fill('Updated Owner');
  const updated = page.waitForResponse(response => response.url().endsWith(`/api/portfolios/${portfolio.id}`) && response.request().method() === 'PUT');
  await page.getByRole('button', { name: 'Save portfolio' }).click();
  expect((await updated).status()).toBe(200);
  await expect(page.getByText('Updated Owner')).toBeVisible();
  await page.reload();
  await expect(page.getByText('Updated Owner')).toBeVisible();
  await page.getByRole('link', { name: 'All portfolios' }).click();
  const filtered = page.waitForResponse(response => response.url().includes('/api/portfolios?') && response.url().includes('search=Journey'));
  await page.getByLabel('Search').fill(name);
  expect((await filtered).ok()).toBeTruthy();
  await page.getByRole('link', { name, exact: true }).click();
  await page.getByRole('button', { name: 'Delete portfolio' }).click();
  const deleted = page.waitForResponse(response => response.url().endsWith(`/api/portfolios/${portfolio.id}`) && response.request().method() === 'DELETE');
  await page.getByRole('button', { name: 'Confirm delete' }).click();
  expect((await deleted).status()).toBe(204);
  await expect(page.getByRole('heading', { name: 'Portfolios' })).toBeVisible();
  expect(errors).toEqual([]);
});
