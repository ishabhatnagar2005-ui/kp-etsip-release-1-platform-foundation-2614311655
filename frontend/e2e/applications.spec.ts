import { expect, test } from '@playwright/test';

test('administrator creates, filters, edits and deletes an application', async ({ page }) => {
  const errors: string[] = [];
  page.on('pageerror', error => errors.push(error.message));
  page.on('console', message => { if (message.type() === 'error') errors.push(message.text()); });
  const password = process.env.E2E_ADMIN_PASSWORD;
  if (!password) throw new Error('Set E2E_ADMIN_PASSWORD to the current administrator password after first-use setup');
  const name = `Journey application ${Date.now()}`;
  await page.goto('/login');
  await page.getByLabel('Email address').fill('admin@ketsip.local');
  await page.getByLabel('Password').fill(password);
  await page.getByRole('button', { name: 'Sign in' }).click();
  await page.getByRole('link', { name: 'Applications', exact: true }).click();
  await page.getByRole('link', { name: 'Create application' }).click();
  await page.getByLabel('Name').fill(name);
  await page.getByLabel('Portfolio').selectOption({ label: 'Payments' });
  await page.getByLabel('Business owner').fill('Journey Business');
  await page.getByLabel('Quality score').fill('84');
  await page.getByLabel('Risk level').selectOption('High');
  const created = page.waitForResponse(response => response.url().endsWith('/api/applications') && response.request().method() === 'POST');
  await page.getByRole('button', { name: 'Save application' }).click();
  const createResponse = await created;
  expect(createResponse.status()).toBe(201);
  const application = await createResponse.json();
  expect(application.name).toBe(name);
  expect(application.qualityScore).toBe(84);
  await expect(page.getByRole('heading', { name })).toBeVisible();
  await page.getByRole('link', { name: 'Edit application' }).click();
  await page.getByLabel('Business owner').fill('Updated Business');
  const updated = page.waitForResponse(response => response.url().endsWith(`/api/applications/${application.id}`) && response.request().method() === 'PUT');
  await page.getByRole('button', { name: 'Save application' }).click();
  const updateResponse = await updated;
  expect(updateResponse.status()).toBe(200);
  expect((await updateResponse.json()).businessOwner).toBe('Updated Business');
  await expect(page.getByText('Updated Business')).toBeVisible();
  await page.reload();
  await expect(page.getByText('Updated Business')).toBeVisible();
  await page.getByRole('link', { name: 'All applications' }).click();
  const filtered = page.waitForResponse(response => response.url().includes('/api/applications?') && new URL(response.url()).searchParams.get('search') === name);
  await page.getByLabel('Search').fill(name);
  const filterResponse = await filtered;
  expect(filterResponse.status()).toBe(200);
  expect((await filterResponse.json()).items.some((item: { id: string }) => item.id === application.id)).toBeTruthy();
  await expect(page.getByRole('link', { name, exact: true })).toBeVisible();
  await page.getByRole('link', { name, exact: true }).click();
  await page.getByRole('button', { name: 'Delete application' }).click();
  const deleted = page.waitForResponse(response => response.url().endsWith(`/api/applications/${application.id}`) && response.request().method() === 'DELETE');
  await page.getByRole('button', { name: 'Confirm delete' }).click();
  expect((await deleted).status()).toBe(204);
  await expect(page.getByRole('heading', { name: 'Applications' })).toBeVisible();
  expect(errors).toEqual([]);
});
